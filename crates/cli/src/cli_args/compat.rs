#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum CompatValueKind {
    Flag,
    RequiredValue,
    OptionalValue,
    OneOrMoreValues,
}

#[derive(Clone, Copy, Debug)]
pub(crate) struct CompatOptionSpec {
    pub(crate) canonical: &'static str,
    pub(crate) aliases: &'static [&'static str],
    pub(crate) short_aliases: &'static [char],
    pub(crate) value_kind: CompatValueKind,
    pub(crate) sample_values: &'static [&'static str],
}

const fn option(
    canonical: &'static str,
    aliases: &'static [&'static str],
    short_aliases: &'static [char],
    value_kind: CompatValueKind,
    sample_values: &'static [&'static str],
) -> CompatOptionSpec {
    CompatOptionSpec {
        canonical,
        aliases,
        short_aliases,
        value_kind,
        sample_values,
    }
}

