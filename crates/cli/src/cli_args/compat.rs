pub(crate) fn ts_top_level_option_specs() -> &'static [CompatOptionSpec] {
    TS_TOP_LEVEL_OPTION_SPECS
}

pub(crate) fn find_ts_top_level_option(name: &str) -> Option<&'static CompatOptionSpec> {
    TS_TOP_LEVEL_OPTION_SPECS
        .iter()
        .find(|spec| spec.canonical == name || spec.aliases.contains(&name))
}

pub(crate) fn find_ts_top_level_short_option(short: char) -> Option<&'static CompatOptionSpec> {
    TS_TOP_LEVEL_OPTION_SPECS
        .iter()
        .find(|spec| spec.short_aliases.contains(&short))
}
